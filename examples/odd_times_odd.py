from manim import *


class OddTimesOdd(Scene):
    def construct(self):
        # ---- Title
        title = Text("Odd × Odd = Odd", font_size=72, t2c={"Odd": YELLOW})
        subtitle = Text("Why multiplying two odd numbers always gives an odd number", font_size=28, color=GREY_B)
        subtitle.next_to(title, DOWN, buff=0.4)
        self.play(Write(title), run_time=1.5)
        self.play(FadeIn(subtitle, shift=UP * 0.3))
        self.wait(1.5)
        self.play(FadeOut(title, subtitle))

        # ---- What makes a number odd: pairs plus one left over
        heading = Text("What makes a number odd?", font_size=44).to_edge(UP, buff=0.6)
        pairs = VGroup(*[Dot(radius=0.2, color=BLUE) for _ in range(6)]).arrange_in_grid(rows=2, cols=3, buff=0.4)
        pairs.shift(LEFT * 0.4 + UP * 0.6)
        extra = Dot(radius=0.2, color=YELLOW).next_to(pairs, RIGHT, buff=0.4).align_to(pairs, UP)
        seven = Text("7 = 2 × 3 + 1", font_size=44, t2c={"+ 1": YELLOW}).next_to(pairs, DOWN, buff=0.7)
        rule = Text("Every odd number is pairs plus one left over:  2k + 1", font_size=32, t2c={"+ 1": YELLOW})
        rule.next_to(seven, DOWN, buff=0.6)
        self.play(Write(heading))
        self.play(LaggedStartMap(GrowFromCenter, pairs, lag_ratio=0.15))
        self.play(FadeIn(extra, scale=2))
        self.play(Indicate(extra, color=YELLOW, scale_factor=1.6))
        self.play(Write(seven))
        self.play(FadeIn(rule, shift=UP * 0.2))
        self.wait(2)
        self.play(FadeOut(heading, pairs, extra, seven, rule))

        # ---- The algebra
        heading2 = Text("Take any two odd numbers", font_size=44).to_edge(UP, buff=0.6)
        line1 = Text("m = 2a + 1,    n = 2b + 1", font_size=40, t2c={"+ 1": YELLOW}).next_to(heading2, DOWN, buff=0.7)
        line2 = Text("m × n = (2a + 1)(2b + 1)", font_size=40, t2c={"+ 1": YELLOW}).next_to(line1, DOWN, buff=0.45)
        line3 = Text("= 4ab + 2a + 2b + 1", font_size=40, t2c={"+ 1": YELLOW}).next_to(line2, DOWN, buff=0.45)
        line4 = Text("= 2(2ab + a + b) + 1", font_size=40, t2c={"+ 1": YELLOW}).next_to(line3, DOWN, buff=0.45)
        line5 = Text("= 2k + 1", font_size=40, t2c={"+ 1": YELLOW}).next_to(line4, DOWN, buff=0.45)
        line3.align_to(line2[3], LEFT)
        line4.align_to(line2[3], LEFT)
        line5.align_to(line2[3], LEFT)
        note3 = Text("multiply out", font_size=26, color=GREY_B).next_to(line3, RIGHT, buff=0.6)
        note4 = Text("take out a 2", font_size=26, color=GREY_B).next_to(line4, RIGHT, buff=0.6)
        note5 = Text("where k = 2ab + a + b", font_size=26, color=GREY_B).next_to(line5, RIGHT, buff=0.6)
        box = SurroundingRectangle(line5, color=YELLOW, buff=0.15)
        self.play(Write(heading2))
        self.play(Write(line1))
        self.wait(0.5)
        self.play(Write(line2))
        self.wait(0.5)
        self.play(Write(line3), FadeIn(note3, shift=LEFT * 0.2))
        self.wait(0.5)
        self.play(Write(line4), FadeIn(note4, shift=LEFT * 0.2))
        self.wait(0.5)
        self.play(Write(line5), FadeIn(note5, shift=LEFT * 0.2))
        self.play(Create(box))
        self.play(Indicate(line5, color=YELLOW))
        self.wait(2)
        self.play(FadeOut(heading2, line1, line2, line3, line4, line5, note3, note4, note5, box))

        # ---- See it with dots: a 3 × 5 grid pairs up except one corner
        heading3 = Text("See it with dots:  3 × 5", font_size=44).to_edge(UP, buff=0.6)
        grid = VGroup(*[Dot(radius=0.18, color=BLUE) for _ in range(15)]).arrange_in_grid(rows=3, cols=5, buff=0.55)
        grid.shift(DOWN * 0.2)
        dominoes = VGroup(*[SurroundingRectangle(VGroup(grid[i], grid[j]), buff=0.12, corner_radius=0.18, color=GREEN)
                            for i, j in [(0, 1), (2, 3), (5, 6), (7, 8), (10, 11), (12, 13), (4, 9)]])
        count = Text("7 pairs + 1 left over = 15, which is odd", font_size=34, t2c={"+ 1": YELLOW}).next_to(grid, DOWN, buff=0.8)
        general = Text("Any odd × odd grid pairs up except one corner dot", font_size=30, color=GREY_B).next_to(count, DOWN, buff=0.35)
        self.play(Write(heading3))
        self.play(LaggedStartMap(FadeIn, grid, lag_ratio=0.05))
        self.play(LaggedStartMap(Create, dominoes, lag_ratio=0.2), run_time=2.5)
        self.play(grid[14].animate.set_color(YELLOW).scale(1.5))
        self.play(Write(count))
        self.play(FadeIn(general, shift=UP * 0.2))
        self.wait(2)
        self.play(FadeOut(heading3, grid, dominoes, count, general))

        # ---- Conclusion
        final = Text("Odd × Odd = Odd", font_size=72, t2c={"Odd": YELLOW})
        proof = Text("(2a + 1)(2b + 1) = 2k + 1", font_size=40, t2c={"+ 1": YELLOW}).next_to(final, DOWN, buff=0.5)
        aside = Text("But odd + odd is even: the two left-over ones make a pair.", font_size=28, color=GREY_B)
        aside.to_edge(DOWN, buff=0.8)
        self.play(Write(final))
        self.play(FadeIn(proof, shift=UP * 0.2))
        self.wait(1.5)
        self.play(FadeIn(aside))
        self.wait(2.5)
